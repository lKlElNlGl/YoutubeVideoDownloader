"""Icon Lab legacy image pipeline from successful v0.3.2, new approved art only.

The Realme 8i previously displayed v0.3.x icons with transparent corners.
Restore its actual resource setup: 128px source, 192px legacy xxxhdpi PNG,
the 04b supersampled renderer, no adaptive XML or background drawables.

The new approved master contains ~8% EXTRA TRANSPARENT MARGINS on each side
and must be fitted into the same 128px/4px-inset footprint as the old source.
Only transparent margins are cropped; the artwork itself is NEVER redrawn.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "iconlab/assets/approved_master_display.webp"
RES = ROOT / "iconlab/src/main/res"
SOURCE_SIZE = 128
SOURCE_INSET = 4
OUTPUT_SIZE = 192
SUPER_SAMPLE = 8
APPROVED_SCALE = 1.06 * (1 - 0.0025)
VARIANTS = tuple(
    (f"{index:02d}", percent / 100.0)
    for index, percent in enumerate(range(96, 107), start=1)
)


def prepare_128_source(source):
    """Fit nontransparent artwork to previous 128px geometry (4px margin)."""
    original = source.convert("RGBA")
    # Ignore only near-invisible remnants from the master conversion when
    # deciding the crop rectangle. Preserve ALL pixels inside that rectangle.
    mask = original.getchannel("A").point(lambda a: 255 if a > 2 else 0)
    bbox = mask.getbbox()
    if bbox is None:
        raise ValueError("approved artwork has no visible pixels")
    artwork = original.crop(bbox)
    limit = SOURCE_SIZE - 2 * SOURCE_INSET
    w, h = artwork.size
    scale = limit / max(w, h)
    new_size = (max(1, round(w * scale)), max(1, round(h * scale)))
    resized = artwork.resize(new_size, Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (SOURCE_SIZE, SOURCE_SIZE), (0, 0, 0, 0))
    canvas.paste(resized, ((SOURCE_SIZE-new_size[0])//2,
                           (SOURCE_SIZE-new_size[1])//2))
    return canvas


def fit_canvas_subpixel(artwork, size, scale):
    """Unmodified Icon Lab v0.3.2 / Icon 04b supersampled PNG renderer."""
    big = size * SUPER_SAMPLE
    side = max(1, round(big * scale))
    resized = artwork.resize((side, side), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    offset = (big - side) // 2
    canvas.paste(resized, (offset, offset))
    return canvas.resize((size, size), Image.Resampling.LANCZOS)


def render_variants(source, output_dir=RES):
    base = prepare_128_source(source)
    icon_dir = output_dir / "mipmap-xxxhdpi"
    icon_dir.mkdir(parents=True, exist_ok=True)
    for pattern in ("lab_top_*.png", "lab_size_*.png",
                    "lab_icon_*.png", "lab_clean_*.png"):
        for old in icon_dir.glob(pattern):
            old.unlink()
    # Delete all adaptive/generated graphics in reused local builds. None
    # exist in a fresh checkout because they are generated by preBuild.
    for directory, pattern in (
        ("mipmap-anydpi-v26", "lab_size_*.xml"),
        ("drawable-nodpi", "lab_foreground_art_*.webp"),
        ("drawable-nodpi", "lab_adaptive_foreground_*.png"),
        ("drawable-nodpi", "lab_background_art.webp"),
        ("drawable", "lab_foreground_*.xml"),
    ):
        target = output_dir / directory
        if target.exists():
            for old in target.glob(pattern):
                old.unlink()
    for number, scale in VARIANTS:
        fit_canvas_subpixel(base, OUTPUT_SIZE, scale).save(
            icon_dir / f"lab_size_{number}.png", optimize=True)
    return base


if __name__ == "__main__":
    if not SOURCE.exists():
        raise SystemExit("Approved master display missing; old-art fallback forbidden")
    with Image.open(SOURCE) as art:
        base = render_variants(art)
    assert base.size == (128, 128)
    print("Generated eleven legacy 192px xxxhdpi icons (v0.3.2 pipeline).")
